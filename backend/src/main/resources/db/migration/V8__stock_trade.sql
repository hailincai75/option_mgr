-- V8 (FEAT-011): stock trades. One row per user-entered stock record: BUY, SELL or TRANSFER_IN (opening holding).
-- amount: user-entered amount incl. fees, always positive (BUY = paid, SELL = received, TRANSFER_IN = total cost);
-- type decides the cash direction. traded_at: UTC; a TRANSFER_IN is recorded at 00:00 New York of its date (Q86).
-- id = entry order; holdings / FIFO lots per (account, symbol) are a replay of this table in (traded_at, id) order and
-- are never stored. The cash effect of BUY / SELL is a cash_ledger_entry with source_type 'STOCK_BUY' / 'STOCK_SELL'
-- and source_id = stock_trade.id (no constraint on source_type, nothing to change there); TRANSFER_IN has none.
-- REAL-DATA MIGRATION: adds a table and widens one check constraint; no existing row or value is changed. The
-- application backs up a file database before running pending migrations (Q60, DatabaseBackupBeforeMigration).

CREATE TABLE stock_trade (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id     BIGINT         NOT NULL,
    type           VARCHAR(12)    NOT NULL,
    symbol         VARCHAR(10)    NOT NULL,
    shares         INTEGER        NOT NULL,
    amount         NUMERIC(19, 2) NOT NULL,
    traded_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    note           VARCHAR(500),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    has_audit_log  BOOLEAN        DEFAULT FALSE NOT NULL,
    CONSTRAINT fk_stock_trade_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT ck_stock_trade_type CHECK (type IN ('BUY', 'SELL', 'TRANSFER_IN')),
    CONSTRAINT ck_stock_trade_shares CHECK (shares > 0 AND shares <= 10000000),
    CONSTRAINT ck_stock_trade_amount CHECK (amount > 0)
);
CREATE INDEX ix_stock_trade_account_symbol ON stock_trade (account_id, symbol, traded_at, id);
CREATE INDEX ix_stock_trade_account_order ON stock_trade (account_id, traded_at, id);

-- Edits / deletions of stock trades are audited as STOCK_TRADE.
ALTER TABLE audit_record DROP CONSTRAINT ck_audit_object_type;
ALTER TABLE audit_record ADD CONSTRAINT ck_audit_object_type
    CHECK (object_type IN ('OPTION_TRADE', 'CASH_TRANSFER', 'ACCOUNT', 'STOCK_TRADE'));
