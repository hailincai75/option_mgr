-- V5 (FEAT-033): multiple accounts. REAL-DATA MIGRATION: every existing row goes into the default account (id 1);
-- no existing id, timestamp, amount, text or audit content is changed. The application backs up a file database
-- before running pending migrations (Q60, DatabaseBackupBeforeMigration); H2 commits each DDL statement, so that
-- backup is the way back if anything below fails.

-- Accounts (Q51): name 1-30 chars, unique case-insensitively via name_key = lower-cased trimmed name (set by the
-- application); optional broker note. No account numbers.
CREATE TABLE account (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(30)  NOT NULL,
    name_key     VARCHAR(30)  NOT NULL,
    broker_note  VARCHAR(50),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_account_name_key UNIQUE (name_key)
);
-- Q52: the default account holds all existing data (and is the only account of an empty database).
INSERT INTO account (id, name, name_key, broker_note, created_at)
    VALUES (1, '默认账户', '默认账户', NULL, CURRENT_TIMESTAMP);
ALTER TABLE account ALTER COLUMN id RESTART WITH 2;

-- cash_account becomes one row per account (same id); its row is the per-account lock of cash-changing writes.
-- The existing row 1 is the default account's.
ALTER TABLE cash_account ADD CONSTRAINT fk_cash_account_account FOREIGN KEY (id) REFERENCES account (id);

-- Every record belongs to exactly one account. Existing rows get account 1 through the column default, which is
-- then removed so the application must always set it.
ALTER TABLE cash_transfer ADD COLUMN account_id BIGINT DEFAULT 1 NOT NULL;
ALTER TABLE cash_transfer ALTER COLUMN account_id DROP DEFAULT;
ALTER TABLE cash_transfer ADD CONSTRAINT fk_cash_transfer_account FOREIGN KEY (account_id) REFERENCES account (id);
CREATE INDEX ix_cash_transfer_account ON cash_transfer (account_id, id);

ALTER TABLE cash_ledger_entry ADD COLUMN account_id BIGINT DEFAULT 1 NOT NULL;
ALTER TABLE cash_ledger_entry ALTER COLUMN account_id DROP DEFAULT;
ALTER TABLE cash_ledger_entry ADD CONSTRAINT fk_cash_ledger_entry_account FOREIGN KEY (account_id) REFERENCES account (id);
CREATE INDEX ix_cash_ledger_account_order ON cash_ledger_entry (account_id, occurred_at, id);

ALTER TABLE option_trade ADD COLUMN account_id BIGINT DEFAULT 1 NOT NULL;
ALTER TABLE option_trade ALTER COLUMN account_id DROP DEFAULT;
ALTER TABLE option_trade ADD CONSTRAINT fk_option_trade_account FOREIGN KEY (account_id) REFERENCES account (id);
CREATE INDEX ix_option_trade_account_contract
    ON option_trade (account_id, symbol, expiration_date, strike, option_type, traded_at, id);

ALTER TABLE audit_record ADD COLUMN account_id BIGINT DEFAULT 1 NOT NULL;
ALTER TABLE audit_record ALTER COLUMN account_id DROP DEFAULT;
ALTER TABLE audit_record ADD CONSTRAINT fk_audit_record_account FOREIGN KEY (account_id) REFERENCES account (id);
CREATE INDEX ix_audit_account_order ON audit_record (account_id, operated_at, id);

-- Q59: account creation / rename are audited (operation CREATE has no "before").
ALTER TABLE audit_record ALTER COLUMN before_json DROP NOT NULL;
ALTER TABLE audit_record DROP CONSTRAINT ck_audit_operation;
ALTER TABLE audit_record ADD CONSTRAINT ck_audit_operation CHECK (operation IN ('CREATE', 'UPDATE', 'DELETE'));
ALTER TABLE audit_record DROP CONSTRAINT ck_audit_object_type;
ALTER TABLE audit_record ADD CONSTRAINT ck_audit_object_type
    CHECK (object_type IN ('OPTION_TRADE', 'CASH_TRANSFER', 'ACCOUNT'));
