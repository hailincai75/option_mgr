-- V2 (FEAT-007): cash account, deposits/withdrawals and the unified cash ledger.

-- Single USD account (Q3/Q4). The row also serves as the lock that serializes every
-- cash-changing transaction (SELECT ... FOR UPDATE), so replay checks never race.
CREATE TABLE cash_account (
    id          BIGINT       NOT NULL PRIMARY KEY,
    currency    VARCHAR(3)   NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
INSERT INTO cash_account (id, currency, created_at) VALUES (1, 'USD', CURRENT_TIMESTAMP);

-- Deposits and withdrawals as entered by the user (amount always positive).
CREATE TABLE cash_transfer (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type         VARCHAR(20)   NOT NULL,
    amount       NUMERIC(19, 2) NOT NULL,
    occurred_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    remark       VARCHAR(500),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_cash_transfer_type CHECK (type IN ('DEPOSIT', 'WITHDRAWAL')),
    CONSTRAINT ck_cash_transfer_amount CHECK (amount > 0)
);

-- Every cash movement from every source. id = entry order; replay order is (occurred_at, id).
-- amount: signed cash change (inflow > 0). frozen_change: signed change of frozen cash
-- (0 for deposits/withdrawals; STO put adds, closing/expiry releases in later features).
-- source_type + source_id point at the originating record (cash_transfer, later trades, ...).
CREATE TABLE cash_ledger_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    source_type    VARCHAR(40)    NOT NULL,
    source_id      BIGINT         NOT NULL,
    amount         NUMERIC(19, 2) NOT NULL,
    frozen_change  NUMERIC(19, 2) NOT NULL DEFAULT 0,
    description    VARCHAR(500),
    remark         VARCHAR(500),
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_cash_ledger_order ON cash_ledger_entry (occurred_at, id);
CREATE INDEX ix_cash_ledger_source ON cash_ledger_entry (source_type, source_id);
