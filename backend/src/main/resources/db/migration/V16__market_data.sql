-- V16 (FEAT-016): automatic delayed quotes (CBOE, Finnhub price fallback) and manual overrides, one set for all
-- accounts. underlying_quote / option_quote hold the latest data per symbol / contract (failures never clear them);
-- the *_close tables hold the 16:20 New York snapshot per day (Q142). market_data_status is a single row (id = 1).
-- REAL-DATA MIGRATION: new tables only; no existing table or row is changed.

CREATE TABLE underlying_quote (
    symbol                VARCHAR(20)                 NOT NULL,
    price                 DECIMAL(19, 6),
    bid                   DECIMAL(19, 6),
    ask                   DECIMAL(19, 6),
    prev_close            DECIMAL(19, 6),
    -- source of price: CBOE / FINNHUB
    price_source          VARCHAR(10),
    quote_time            TIMESTAMP(6) WITH TIME ZONE,
    last_price_success_at TIMESTAMP(6) WITH TIME ZONE,
    last_chain_success_at TIMESTAMP(6) WITH TIME ZONE,
    last_attempt_at       TIMESTAMP(6) WITH TIME ZONE,
    last_price_failed     BOOLEAN                     NOT NULL,
    last_chain_failed     BOOLEAN                     NOT NULL,
    last_cboe_result      VARCHAR(20),
    last_finnhub_result   VARCHAR(20),
    last_failure_detail   VARCHAR(500),
    manual_price          DECIMAL(19, 6),
    manual_entered_at     TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_underlying_quote PRIMARY KEY (symbol),
    CONSTRAINT ck_underlying_quote_source CHECK (price_source IS NULL OR price_source IN ('CBOE', 'FINNHUB')),
    CONSTRAINT ck_underlying_quote_manual CHECK ((manual_price IS NULL) = (manual_entered_at IS NULL))
);

CREATE TABLE option_quote (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    symbol            VARCHAR(20)                 NOT NULL,
    expiration_date   DATE                        NOT NULL,
    -- normalized (no trailing zeros) so 50 and 50.0 are the same contract
    strike            DECIMAL(19, 6)              NOT NULL,
    option_type       VARCHAR(4)                  NOT NULL,
    occ_code          VARCHAR(40),
    bid               DECIMAL(19, 6),
    ask               DECIMAL(19, 6),
    last_price        DECIMAL(19, 6),
    theo              DECIMAL(19, 6),
    iv                DECIMAL(19, 8),
    delta             DECIMAL(19, 8),
    gamma             DECIMAL(19, 8),
    theta             DECIMAL(19, 8),
    vega              DECIMAL(19, 8),
    rho               DECIMAL(19, 8),
    volume            BIGINT,
    open_interest     BIGINT,
    -- NULL = never quoted (a row may exist only for a manual mark)
    quote_time        TIMESTAMP(6) WITH TIME ZONE,
    fetched_at        TIMESTAMP(6) WITH TIME ZONE,
    -- not NULL = MISSING_FROM_SOURCE since this run
    missing_since     TIMESTAMP(6) WITH TIME ZONE,
    manual_mark       DECIMAL(19, 6),
    manual_entered_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_option_quote PRIMARY KEY (id),
    CONSTRAINT uq_option_quote_contract UNIQUE (symbol, expiration_date, strike, option_type),
    CONSTRAINT ck_option_quote_type CHECK (option_type IN ('CALL', 'PUT')),
    CONSTRAINT ck_option_quote_manual CHECK ((manual_mark IS NULL) = (manual_entered_at IS NULL))
);

CREATE TABLE underlying_quote_close (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    snapshot_date DATE                        NOT NULL,
    symbol        VARCHAR(20)                 NOT NULL,
    price         DECIMAL(19, 6),
    bid           DECIMAL(19, 6),
    ask           DECIMAL(19, 6),
    prev_close    DECIMAL(19, 6),
    price_source  VARCHAR(10),
    quote_time    TIMESTAMP(6) WITH TIME ZONE,
    captured_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_underlying_quote_close PRIMARY KEY (id),
    CONSTRAINT uq_underlying_quote_close UNIQUE (snapshot_date, symbol)
);

CREATE TABLE option_quote_close (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    snapshot_date   DATE                        NOT NULL,
    symbol          VARCHAR(20)                 NOT NULL,
    expiration_date DATE                        NOT NULL,
    strike          DECIMAL(19, 6)              NOT NULL,
    option_type     VARCHAR(4)                  NOT NULL,
    occ_code        VARCHAR(40),
    bid             DECIMAL(19, 6),
    ask             DECIMAL(19, 6),
    last_price      DECIMAL(19, 6),
    theo            DECIMAL(19, 6),
    iv              DECIMAL(19, 8),
    delta           DECIMAL(19, 8),
    gamma           DECIMAL(19, 8),
    theta           DECIMAL(19, 8),
    vega            DECIMAL(19, 8),
    rho             DECIMAL(19, 8),
    volume          BIGINT,
    open_interest   BIGINT,
    quote_time      TIMESTAMP(6) WITH TIME ZONE,
    captured_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_option_quote_close PRIMARY KEY (id),
    CONSTRAINT uq_option_quote_close UNIQUE (snapshot_date, symbol, expiration_date, strike, option_type)
);

CREATE TABLE market_data_status (
    id              SMALLINT                    NOT NULL,
    last_attempt_at TIMESTAMP(6) WITH TIME ZONE,
    last_success_at TIMESTAMP(6) WITH TIME ZONE,
    last_refresh_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT pk_market_data_status PRIMARY KEY (id),
    CONSTRAINT ck_market_data_status_single CHECK (id = 1)
);

