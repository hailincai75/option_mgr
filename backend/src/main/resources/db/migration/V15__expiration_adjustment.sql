-- V15 (FEAT-043): adjusting a contract's expiration date when it falls on an ACTIVE ad-hoc closure (exception to Q43).
-- expiration_adjustment: one row per adjustment; the unique key on the NEW contract makes "only once" (Q131) hold
-- even if the new date is later detected as an ad-hoc closure too.
-- audit_record_object: further objects an audit record refers to (an adjustment changes several option trades), so
-- GET /api/audit-log?objectType=OPTION_TRADE&objectId=X also finds the adjustment of every changed trade.
-- audit_record.detail_json: operation-specific data (the "expirationAdjustment" object of ADJUST_EXPIRATION).
-- REAL-DATA MIGRATION: new tables, a new nullable column and a widened / relaxed constraint only; no row changes.

ALTER TABLE audit_record ALTER COLUMN operation SET DATA TYPE VARCHAR(20);
ALTER TABLE audit_record DROP CONSTRAINT ck_audit_operation;
ALTER TABLE audit_record ADD CONSTRAINT ck_audit_operation
    CHECK (operation IN ('CREATE', 'UPDATE', 'DELETE', 'ADJUST_EXPIRATION'));
ALTER TABLE audit_record ADD COLUMN detail_json VARCHAR(10000);

CREATE TABLE audit_record_object (
    audit_record_id BIGINT      NOT NULL,
    object_type     VARCHAR(20) NOT NULL,
    object_id       BIGINT      NOT NULL,
    CONSTRAINT pk_audit_record_object PRIMARY KEY (audit_record_id, object_type, object_id),
    CONSTRAINT fk_audit_record_object_audit FOREIGN KEY (audit_record_id) REFERENCES audit_record (id)
);
CREATE INDEX ix_audit_record_object_object ON audit_record_object (object_type, object_id);

CREATE TABLE expiration_adjustment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT         NOT NULL,
    symbol              VARCHAR(10)    NOT NULL,
    strike              NUMERIC(10, 3) NOT NULL,
    option_type         VARCHAR(4)     NOT NULL,
    old_expiration_date DATE           NOT NULL,
    new_expiration_date DATE           NOT NULL,
    adjusted_at         TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    audit_record_id     BIGINT         NOT NULL,
    CONSTRAINT fk_expiration_adjustment_account FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT fk_expiration_adjustment_audit FOREIGN KEY (audit_record_id) REFERENCES audit_record (id),
    CONSTRAINT ck_expiration_adjustment_type CHECK (option_type IN ('CALL', 'PUT')),
    CONSTRAINT ck_expiration_adjustment_dates CHECK (new_expiration_date < old_expiration_date),
    CONSTRAINT uq_expiration_adjustment_new_contract
        UNIQUE (account_id, symbol, new_expiration_date, strike, option_type)
);
