-- V3 (FEAT-001): option trades. FEAT-001 writes only opens (BTO / STO); FEAT-004 adds closes (BTC / STC)
-- to the same table, so positions per contract are a replay of this table in (traded_at, id) order.
-- Contract identity = symbol + expiration_date + strike + option_type. Each open is its own row (future FIFO lot).
-- net_amount: user-entered net incl. fees, always positive; action decides cash in/out.
-- The cash effect lives in cash_ledger_entry (source_type 'OPTION_OPEN', source_id = option_trade.id);
-- no FK between them because source_id is polymorphic.
CREATE TABLE option_trade (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol           VARCHAR(10)    NOT NULL,
    expiration_date  DATE           NOT NULL,
    strike           NUMERIC(10, 3) NOT NULL,
    option_type      VARCHAR(4)     NOT NULL,
    action           VARCHAR(3)     NOT NULL,
    contracts        INTEGER        NOT NULL,
    multiplier       INTEGER        NOT NULL,
    net_amount       NUMERIC(19, 2) NOT NULL,
    traded_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    note             VARCHAR(500),
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_option_trade_type CHECK (option_type IN ('CALL', 'PUT')),
    CONSTRAINT ck_option_trade_action CHECK (action IN ('BTO', 'STO', 'BTC', 'STC')),
    CONSTRAINT ck_option_trade_strike CHECK (strike > 0),
    CONSTRAINT ck_option_trade_contracts CHECK (contracts > 0),
    CONSTRAINT ck_option_trade_multiplier CHECK (multiplier > 0),
    CONSTRAINT ck_option_trade_net CHECK (net_amount > 0)
);
CREATE INDEX ix_option_trade_contract ON option_trade (symbol, expiration_date, strike, option_type, traded_at, id);
