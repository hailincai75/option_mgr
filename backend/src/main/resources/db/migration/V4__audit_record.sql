-- V4 (FEAT-005): immutable audit records of edits and deletions (Q12, Q42, Q44).
-- object_type + object_id point at the edited/deleted record (option_trade or cash_transfer; may no longer exist).
-- before_json / after_json: full content before / after (after is NULL for a deletion).
-- changes_json: changed fields for display; side_effects_json: system corrections caused by the change (Q42).
CREATE TABLE audit_record (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    operation          VARCHAR(10)    NOT NULL,
    object_type        VARCHAR(20)    NOT NULL,
    object_id          BIGINT         NOT NULL,
    summary            VARCHAR(200)   NOT NULL,
    before_json        VARCHAR(10000) NOT NULL,
    after_json         VARCHAR(10000),
    changes_json       VARCHAR(10000) NOT NULL,
    side_effects_json  VARCHAR(10000) NOT NULL,
    CONSTRAINT ck_audit_operation CHECK (operation IN ('UPDATE', 'DELETE')),
    CONSTRAINT ck_audit_object_type CHECK (object_type IN ('OPTION_TRADE', 'CASH_TRANSFER'))
);
CREATE INDEX ix_audit_order ON audit_record (operated_at, id);
CREATE INDEX ix_audit_object ON audit_record (object_type, object_id);
