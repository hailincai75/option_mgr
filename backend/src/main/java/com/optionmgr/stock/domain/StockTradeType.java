package com.optionmgr.stock.domain;

import com.optionmgr.cash.domain.CashSourceType;
import com.optionmgr.common.money.Money;
import java.math.BigDecimal;
import java.util.Optional;

/**
 * FEAT-011 kind of stock record. The user always enters a positive amount (Q67): BUY = paid incl. fees, SELL =
 * received net of fees, TRANSFER_IN = total cost of an opening holding (Q71, no cash effect). Persisted by name.
 */
public enum StockTradeType {
    BUY("买入"),
    SELL("卖出"),
    TRANSFER_IN("转入"),
    /** FEAT-013: the lot bought by a short-put assignment; generated only, cash is on the OPTION_ASSIGN entry. */
    ASSIGN_BUY("指派买入"),
    /** FEAT-041: the shares delivered by a short-call assignment; generated only, cash is on the OPTION_ASSIGN entry. */
    ASSIGN_SELL("指派卖出"),
    /** FEAT-014: the lot bought by a long-call exercise; generated only, cash is on the OPTION_EXERCISE entry. */
    EXERCISE_BUY("行权买入"),
    /** FEAT-014: the shares sold by a long-put exercise; generated only, cash is on the OPTION_EXERCISE entry. */
    EXERCISE_SELL("行权卖出");

    private final String label;

    StockTradeType(String label) {
        this.label = label;
    }

    /** Chinese label: 买入 / 卖出 / 转入. */
    public String label() {
        return label;
    }

    /** BUY, TRANSFER_IN, ASSIGN_BUY and EXERCISE_BUY create a FIFO lot; the sales consume lots. */
    public boolean createsLot() {
        return !isSale();
    }

    /** SELL and (FEAT-041) ASSIGN_SELL take shares from the FIFO lots and have a sold cost / realized P&amp;L. */
    public boolean isSale() {
        return this == SELL || this == ASSIGN_SELL || this == EXERCISE_SELL;
    }

    /**
     * FEAT-013 / FEAT-041 / FEAT-014: generated by an assignment or an exercise; edited / deleted only through that
     * option record.
     */
    public boolean isGenerated() {
        return this == ASSIGN_BUY || this == ASSIGN_SELL || isFromExercise();
    }

    /** FEAT-014: generated by an exercise (EXR). */
    public boolean isFromExercise() {
        return this == EXERCISE_BUY || this == EXERCISE_SELL;
    }

    /** Signed change of total cash, scale 2: BUY -amount, SELL +amount, TRANSFER_IN 0. */
    public BigDecimal cashChange(BigDecimal amount) {
        return switch (this) {
            case BUY -> Money.of(amount).negate();
            case SELL -> Money.of(amount);
            case TRANSFER_IN, ASSIGN_BUY, ASSIGN_SELL, EXERCISE_BUY, EXERCISE_SELL -> Money.ZERO;
        };
    }

    /** Ledger source type of the record's cash entry; TRANSFER_IN has no entry. */
    public Optional<CashSourceType> ledgerSource() {
        return switch (this) {
            case BUY -> Optional.of(CashSourceType.STOCK_BUY);
            case SELL -> Optional.of(CashSourceType.STOCK_SELL);
            case TRANSFER_IN, ASSIGN_BUY, ASSIGN_SELL, EXERCISE_BUY, EXERCISE_SELL -> Optional.empty();
        };
    }

    /** Ledger description, e.g. "买入 200 股 IXQZ". */
    public String describe(int shares, String symbol) {
        return label + " " + shares + " 股 " + symbol;
    }
}
